-- Preparation only: NOT applied to production by this PR.
-- The scheduler must continue using morning_reports.kakao_sent_at until a
-- separately reviewed rollout switches it to this delivery state table.
CREATE TABLE IF NOT EXISTS public.kakao_delivery_attempts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    report_date date NOT NULL,
    attempt_id uuid NOT NULL UNIQUE,
    status text NOT NULL DEFAULT 'pending',
    lease_expires_at timestamptz,
    started_at timestamptz,
    completed_at timestamptz,
    last_error_code text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT kakao_delivery_attempts_status_check CHECK (
        status IN ('pending', 'sending', 'sent', 'uncertain', 'failed_before_send')
    ),
    CONSTRAINT kakao_delivery_attempts_date_owner_attempt_unique UNIQUE (user_id, report_date, attempt_id)
);

-- One active or confirmed attempt per user/day. Multiple historical attempts
-- are possible only after explicit resolution to failed_before_send.
CREATE UNIQUE INDEX IF NOT EXISTS kakao_delivery_attempts_one_active_per_day
ON public.kakao_delivery_attempts (user_id, report_date)
WHERE status IN ('pending', 'sending', 'sent', 'uncertain');

CREATE INDEX IF NOT EXISTS kakao_delivery_attempts_owner_date_idx
ON public.kakao_delivery_attempts (user_id, report_date DESC);

ALTER TABLE public.kakao_delivery_attempts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.kakao_delivery_attempts FROM anon, authenticated;
-- Only trusted backend service-role connections may manipulate attempts.
-- Do not create public client-side RLS policies for this table.
